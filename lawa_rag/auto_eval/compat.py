"""Compatibility export from V1 generated suites to legacy EvalExample rows."""

from __future__ import annotations

from pathlib import Path
from typing import Any, Sequence

from .cases import GeneratedEvalCase
from .corpus import CorpusSnapshot, EvidenceUnit
from .suite import EvalSuite


_QUERY_TYPE = {
    "fact": "fact",
    "compare": "synthesis",
    "synthesis": "synthesis",
    "multimodal": "multimodal",
}

_GOLD_FIELD = {
    "chunk_records": "gold_chunk_ids",
    "evidence_span_records": "gold_span_ids",
    "parent_records": "gold_parent_ids",
    "media_records": "gold_media_ids",
    "page_card_records": "gold_page_card_ids",
    "action_records": "gold_action_ids",
}


def to_eval_example(case: GeneratedEvalCase, snapshot: CorpusSnapshot):
    from pipeline.evaluation.dataset import EvalExample

    evidence = snapshot.evidence_map()
    selected = [evidence[item] for item in case.evidence_ids if item in evidence]
    gold = _gold_ids(selected, snapshot)
    metadata = {
        "auto_eval_schema": case.schema_version,
        "persona_id": case.persona_id,
        "scenario_id": case.scenario_id,
        "difficulty": case.target_difficulty,
        "difficulty_features": case.measured_difficulty.to_dict(),
        "evidence_quotes": [
            {"source_key": citation.evidence_id, "quote": citation.quote}
            for citation in case.citations
        ],
        "answer_must_include": list(case.answer_must_include),
        "answer_must_not_include": list(case.answer_must_not_include),
        "answer_should_cover": list(case.answer_should_cover),
        "citation_requirements": list(case.citation_requirements),
        "expected_response_structure": case.expected_response_structure,
        "review_status": case.review_status,
    }
    return EvalExample(
        id=case.case_id,
        query=case.query,
        query_type=_QUERY_TYPE.get(case.task, "scoped"),
        language=case.language,
        source_type=_source_type(case, selected, snapshot),
        no_answer=not case.answerable,
        reference_answer=case.reference_answer,
        notes="Generated by the grounded Lawa auto-evaluation framework.",
        metadata=metadata,
        **gold,
    ).normalized()


def export_eval_examples(
    suite: EvalSuite,
    snapshot: CorpusSnapshot,
    output_path: str | Path,
    *,
    allow_unreviewed: bool = False,
) -> Path:
    from pipeline.evaluation.dataset import write_eval_examples

    unreviewed = [item.case_id for item in suite.cases if item.review_status == "needs_review"]
    if unreviewed and not allow_unreviewed:
        raise ValueError(
            f"Suite has {len(unreviewed)} cases requiring review; approve them before export"
        )
    examples = [to_eval_example(case, snapshot) for case in suite.cases]
    output = Path(output_path).expanduser().resolve()
    write_eval_examples(output, examples)
    return output


def _gold_ids(selected: Sequence[EvidenceUnit], snapshot: CorpusSnapshot) -> dict[str, Any]:
    output = {field: [] for field in _GOLD_FIELD.values()}
    output.update(
        {
            "gold_document_revision_ids": [],
            "gold_section_ids": [],
        }
    )
    source_map = snapshot.source_map()
    for unit in selected:
        field = _GOLD_FIELD.get(str(unit.metadata.get("record_group") or ""))
        if field:
            output[field].append(unit.evidence_id)
        source = source_map.get(unit.source_id)
        revision_id = source.revision_id if source is not None else unit.source_id
        output["gold_document_revision_ids"].append(revision_id)
        if unit.section_id:
            output["gold_section_ids"].append(unit.section_id)
    return {key: list(dict.fromkeys(value)) for key, value in output.items()}


def _source_type(case, selected, snapshot) -> str:
    if not case.answerable:
        return "none"
    source_map = snapshot.source_map()
    kinds = {
        source_map[item.source_id].source_type
        for item in selected
        if item.source_id in source_map
    }
    if kinds == {"webpage"}:
        return "webpage"
    if kinds == {"pdf"}:
        return "pdf"
    if {item.kind for item in selected}.intersection({"media", "image"}) and len(kinds) <= 1:
        return "image"
    return "mixed"


__all__ = ["export_eval_examples", "to_eval_example"]
